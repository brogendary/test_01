#include <iostream>
using namespace std;

int main () {

    // assignment
    int a = 10;
    // assignment operator
    // variabel = variabel

    a += 3;
    cout << "tambah 3 = " << a << endl;

    a -= 3;
    cout << "kurang 3 = " << a << endl;
    
    a /= 3;
    cout << "bagi 3 = " << a << endl;

    a *= 3;
    cout << "kali 3 = " << a << endl;

    a &= 3;
    cout << "modulus 3 = " << a << endl;



    return 0;
}