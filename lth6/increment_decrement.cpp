#include <iostream>
using namespace std;

int main() {

    int a = 5;
    int b = 5;

    // increment bisa -- atau ++
    // postincrement
    cout << a << endl;
    cout << a++ << endl;
    cout << a << endl;

    cout << endl;

    // preincrement
    cout << b << endl;
    cout << ++b << endl;
    cout << b <<  endl;

    

    return 0;
}